public class AddStaffModel {
    private int emId;
    private String emFullName;
    private String emEmail;
    private String emPassword;
    private String emPhoneNumber;
    private String emAddress;
    private String emRole;

    // Getters and setters
    public int getEmId() { return emId; }
    public void setEmId(int emId) { this.emId = emId; }

    public String getEmFullName() { return emFullName; }
    public void setEmFullName(String emFullName) { this.emFullName = emFullName; }

    public String getEmEmail() { return emEmail; }
    public void setEmEmail(String emEmail) { this.emEmail = emEmail; }

    public String getEmPassword() { return emPassword; }
    public void setEmPassword(String emPassword) { this.emPassword = emPassword; }

    public String getEmPhoneNumber() { return emPhoneNumber; }
    public void setEmPhoneNumber(String emPhoneNumber) { this.emPhoneNumber = emPhoneNumber; }

    public String getEmAddress() { return emAddress; }
    public void setEmAddress(String emAddress) { this.emAddress = emAddress; }

    public String getEmRole() { return emRole; }
    public void setEmRole(String emRole) { this.emRole = emRole; }
}
